#!/usr/bin/env python3
"""
Embeds source/payloads/*.elf into backend/src/bundled_payloads.cpp so the
bundled payloads (ftpsrv, klogsrv, ...) ship inside ProsperoMgr's own ELF
and get written out to bundled_dir on every startup.

Usage: python3 tools/gen_payloads.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAYLOADS_DIR = ROOT / "payloads"
OUT_FILE = ROOT / "backend" / "src" / "bundled_payloads.cpp"


def c_identifier(name: str) -> str:
    return "kPayload_" + "".join(c if c.isalnum() else "_" for c in name)


def emit_byte_array(out, name: str, data: bytes) -> None:
    out.write(f"const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 20):
        chunk = data[i : i + 20]
        out.write("  " + ",".join(str(b) for b in chunk) + ",\n")
    out.write("};\n")


def main() -> int:
    files = sorted(PAYLOADS_DIR.glob("*.elf"))
    if not files:
        print(f"error: no .elf files in {PAYLOADS_DIR}", file=sys.stderr)
        return 1

    entries = []  # (filename, c_name, size)

    with OUT_FILE.open("w") as out:
        out.write(
            "// GENERATED by tools/gen_payloads.py from source/payloads/ — do not hand-edit.\n"
            "// Re-run after adding/updating a bundled payload.\n\n"
            '#include "bundled_payloads.hpp"\n\n'
            "#include <fstream>\n\n"
            "namespace prospero {\n\n"
            "namespace {\n\n"
        )

        for path in files:
            data = path.read_bytes()
            name = c_identifier(path.name)
            emit_byte_array(out, name, data)
            entries.append((path.name, name, len(data)))

        out.write(
            "\nstruct BundledPayload {\n"
            "    const char *filename;\n"
            "    const unsigned char *data;\n"
            "    unsigned int size;\n"
            "};\n\n"
            "const BundledPayload kBundledPayloads[] = {\n"
        )
        for filename, name, size in entries:
            out.write(f'    {{"{filename}", {name}, {size}}},\n')
        out.write(
            "};\n"
            "constexpr size_t kBundledPayloadsCount = sizeof(kBundledPayloads) / sizeof(kBundledPayloads[0]);\n\n"
            "} // namespace\n\n"
            "void InstallBundledPayloads(const std::string &bundled_dir) {\n"
            "    for (size_t i = 0; i < kBundledPayloadsCount; i++) {\n"
            "        const BundledPayload &p = kBundledPayloads[i];\n"
            "        std::ofstream out(bundled_dir + \"/\" + p.filename, std::ios::binary | std::ios::trunc);\n"
            "        out.write(reinterpret_cast<const char *>(p.data), p.size);\n"
            "    }\n"
            "}\n\n"
            "} // namespace prospero\n"
        )

    total_bytes = sum(size for _, _, size in entries)
    print(f"wrote {OUT_FILE.relative_to(ROOT)}: {len(entries)} payloads, {total_bytes} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
