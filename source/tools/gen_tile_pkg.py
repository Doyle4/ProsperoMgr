#!/usr/bin/env python3
"""
Embeds dist/ProsperoMgr.pkg into backend/src/bundled_tile_pkg.cpp so the
home-screen tile PKG ships inside ProsperoMgr's own ELF and gets installed
on first boot (see tile_pkg.cpp).

Usage: python3 tools/gen_tile_pkg.py
"""

import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG_FILE = ROOT.parent / "dist" / "ProsperoMgr.pkg"
OUT_FILE = ROOT / "backend" / "src" / "bundled_tile_pkg.cpp"


def emit_byte_array(out, name: str, data: bytes) -> None:
    out.write(f"const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 20):
        chunk = data[i : i + 20]
        out.write("  " + ",".join(str(b) for b in chunk) + ",\n")
    out.write("};\n")


def main() -> int:
    if not PKG_FILE.exists():
        print(f"error: {PKG_FILE} not found — build it first (see pkg-source/README.md)", file=sys.stderr)
        return 1

    data = PKG_FILE.read_bytes()
    compressed = zlib.compress(data, level=9)

    with OUT_FILE.open("w") as out:
        out.write(
            "// GENERATED by tools/gen_tile_pkg.py from dist/ProsperoMgr.pkg — do not hand-edit.\n"
            "// Re-run after rebuilding the tile PKG (see pkg-source/README.md).\n\n"
            '#include "bundled_tile_pkg.hpp"\n\n'
            "namespace prospero {\n\n"
        )
        emit_byte_array(out, "kTilePkg", compressed)
        out.write(f"const unsigned int kTilePkgSize = {len(compressed)}u;\n")
        out.write(f"const unsigned int kTilePkgRawSize = {len(data)}u;\n\n")
        out.write("} // namespace prospero\n")

    saved_pct = (1 - len(compressed) / len(data)) * 100 if data else 0
    print(f"wrote {OUT_FILE.relative_to(ROOT.parent)}: {len(compressed)} bytes "
          f"({len(data)} uncompressed, {saved_pct:.0f}% smaller)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
